from dataclasses import field as _dc_field
import json as _json

from integrations.md_to_latex import md_to_latex_body, count_image_anchors


@dataclass
class PackageBuildResult:
    success: bool
    package_id: str
    env_info: dict
    chosen_font: str
    final_fallback: str
    cascade: list
    tex_path: Path
    pdf_path: Path | None
    log_path: Path | None
    pdf_bytes: int
    attempts: int
    max_attempts: int
    build_history: list = _dc_field(default_factory=list)
    fix_notes: list = _dc_field(default_factory=list)
    image_anchors_md: int = 0
    image_anchors_tex: int = 0
    image_anchors_first_in_block: bool = False
    expected_images: list = _dc_field(default_factory=list)
    generated_at: str = ""


def _fill_template(template: str, *, main_font: str, english_font: str,
                   mono_font: str, pdf_title: str, pdf_subtitle: str,
                   body: str) -> str:
    """Substitute {{...}} placeholders in templates/package_pdf_template.tex."""
    return (
        template
        .replace("{{MAIN_FONT}}", main_font)
        .replace("{{ENGLISH_FONT}}", english_font)
        .replace("{{MONO_FONT}}", mono_font)
        .replace("{{PDF_TITLE}}", pdf_title)
        .replace("{{PDF_SUBTITLE}}", pdf_subtitle)
        .replace("{{BODY}}", body)
    )


def _image_first_in_each_block(tex: str) -> bool:
    """Check whether every `\subsection*{<N>. Page <P> — original slide anchor}` heading
    is followed (after blanks) by a `\begin{center}` / `\includegraphics{...}` line."""
    import re as _re
    lines = tex.splitlines()
    anchors_seen = 0
    anchors_ok = 0
    pat = _re.compile(r"\\subsection\*\{\s*\d+\.\s+Page\s+\d+\s+—\s+original slide anchor\s*\}")
    for i, line in enumerate(lines):
        if pat.search(line):
            anchors_seen += 1
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j < len(lines) and ("\\begin{center}" in lines[j] or "\\includegraphics" in lines[j]):
                anchors_ok += 1
    return anchors_seen > 0 and anchors_ok == anchors_seen


def run_package_build(run_dir, project_root, package_id: str,
                      *, max_attempts: int = 3) -> PackageBuildResult:
    """Build a single package PDF (Phase 5B).

    Pipeline: read content_md/<package_id>_extended_fa.md ->
    md_to_latex_body -> fill templates/package_pdf_template.tex ->
    write latex/<package_id>_extended_fa.tex -> xelatex with up to
    `max_attempts` retries (each retry consults integrations/auto_fixer_latex).
    On success the PDF is copied to package_pdfs/<package_id>_extended_fa.pdf.
    """
    run_dir = Path(run_dir).resolve()
    project_root = Path(project_root).resolve()

    md_path = run_dir / "content_md" / f"{package_id}_extended_fa.md"
    js_path = run_dir / "content_json" / f"{package_id}_extended_fa.json"
    if not md_path.exists():
        raise FileNotFoundError(f"content_md missing: {md_path}")
    md_text = md_path.read_text(encoding="utf-8")
    n_imgs_md = count_image_anchors(md_text)
    body = md_to_latex_body(md_text)

    # Header info from the JSON sidecar.
    pdf_title = package_id
    pdf_subtitle = ""
    expected_images: list = []
    if js_path.exists():
        try:
            js = _json.loads(js_path.read_text(encoding="utf-8"))
            pdf_title = js.get("package_title") or package_id
            expected_images = [f"page_{n:03d}.png" for n in js.get("source_pages", [])]
            pdf_subtitle = f"{package_id} \\ extracted from Persian extended content"
        except Exception:
            pass
    # Escape LaTeX specials in the title (it may contain "_" or "&").
    def _esc(s: str) -> str:
        return s.replace("\\", "/").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")
    pdf_title_tex = _esc(pdf_title)
    pdf_subtitle_tex = _esc(pdf_subtitle)

    env_info = detect_xelatex()
    cascade, english_font = _load_font_cascade(project_root)
    chosen_font = detect_persian_font(cascade, final_fallback=SMOKE_FALLBACK_FONT)
    chosen_english = detect_persian_font([english_font], final_fallback=SMOKE_FALLBACK_FONT)
    mono_font = detect_persian_font(["Fira Code", "Consolas", "Courier New"],
                                    final_fallback=SMOKE_FALLBACK_FONT)

    latex_dir = run_dir / "latex"
    pdf_dir = run_dir / "package_pdfs"
    latex_dir.mkdir(parents=True, exist_ok=True)
    pdf_dir.mkdir(parents=True, exist_ok=True)

    template_path = project_root / "templates" / "package_pdf_template.tex"
    template = template_path.read_text(encoding="utf-8")
    current_tex = _fill_template(
        template,
        main_font=chosen_font,
        english_font=chosen_english,
        mono_font=mono_font,
        pdf_title=pdf_title_tex,
        pdf_subtitle=pdf_subtitle_tex,
        body=body,
    )

    tex_path = latex_dir / f"{package_id}_extended_fa.tex"
    atomic_write_text(tex_path, current_tex)

    n_imgs_tex = current_tex.count("\\includegraphics")
    image_first_ok = _image_first_in_each_block(current_tex)

    fix_notes: list = []
    build_history: list = []
    br = None
    for attempt in range(1, max_attempts + 1):
        br = run_xelatex(tex_path, latex_dir)
        build_history.append(br)
        if br.success:
            break
        decision = propose_fix(
            build_result=br,
            current_tex=current_tex,
            font_cascade=cascade,
            chosen_font=chosen_font,
            final_fallback=SMOKE_FALLBACK_FONT,
        )
        fix_notes.append(f"attempt {attempt}: {decision.reason}" + (f" — {decision.note}" if decision.note else ""))
        if not (decision.applied and decision.new_tex):
            break
        current_tex = decision.new_tex
        atomic_write_text(tex_path, current_tex)
        # If the fix swapped the font, update chosen_font for the next round.
        for f in cascade + [SMOKE_FALLBACK_FONT]:
            if f"\\setmainfont{{{f}}}" in current_tex:
                chosen_font = f

    final_pdf_path = None
    pdf_bytes = 0
    src_pdf = latex_dir / f"{package_id}_extended_fa.pdf"
    if src_pdf.exists() and src_pdf.stat().st_size > 0:
        target = pdf_dir / f"{package_id}_extended_fa.pdf"
        target.write_bytes(src_pdf.read_bytes())
        final_pdf_path = target
        pdf_bytes = target.stat().st_size

    # Recompute final image-anchor stats from the on-disk .tex (auto_fixer may
    # have rewritten it).
    final_tex = tex_path.read_text(encoding="utf-8")
    n_imgs_tex_final = final_tex.count("\\includegraphics")
    image_first_ok_final = _image_first_in_each_block(final_tex)

    return PackageBuildResult(
        success=bool(final_pdf_path and pdf_bytes > 0),
        package_id=package_id,
        env_info=env_info,
        chosen_font=chosen_font,
        final_fallback=SMOKE_FALLBACK_FONT,
        cascade=cascade,
        tex_path=tex_path,
        pdf_path=final_pdf_path,
        log_path=br.log_path if br else None,
        pdf_bytes=pdf_bytes,
        attempts=len(build_history),
        max_attempts=max_attempts,
        build_history=build_history,
        fix_notes=fix_notes,
        image_anchors_md=n_imgs_md,
        image_anchors_tex=n_imgs_tex_final,
        image_anchors_first_in_block=image_first_ok_final,
        expected_images=expected_images,
        generated_at=iso_now(),
    )



