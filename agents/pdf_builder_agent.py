@dataclass
class AllPackagesResult:
    success: bool
    results: list
    n_packages: int
    n_success: int
    n_fail: int
    generated_at: str = ""


def run_all_packages(run_dir, project_root, *, max_attempts: int = 3,
                     skip_existing: bool = True) -> AllPackagesResult:
    """Build a PDF for every package_NNN that has a content_md file.

    If skip_existing is True (the default), a package whose PDF already
    exists in package_pdfs/ is left alone - this preserves Phase 5B's
    package_001 build instead of rebuilding it on the same run.

    Returns AllPackagesResult with per-package PackageBuildResult in
    `results` (in package_id order).
    """
    run_dir = Path(run_dir).resolve()
    project_root = Path(project_root).resolve()

    md_dir = run_dir / "content_md"
    pdf_dir = run_dir / "package_pdfs"

    md_files = sorted(md_dir.glob("package_*_extended_fa.md"))
    results: list = []
    n_success = n_fail = 0

    for md_path in md_files:
        # extract package_id: package_NNN
        name = md_path.stem  # package_NNN_extended_fa
        pkg_id = name.replace("_extended_fa", "")
        target_pdf = pdf_dir / f"{pkg_id}_extended_fa.pdf"

        if skip_existing and target_pdf.exists() and target_pdf.stat().st_size > 0:
            # Wrap an "already built" placeholder.
            results.append(PackageBuildResult(
                success=True,
                package_id=pkg_id,
                env_info=detect_xelatex(),
                chosen_font="(preserved from prior build)",
                final_fallback=SMOKE_FALLBACK_FONT,
                cascade=[],
                tex_path=(run_dir / "latex" / f"{pkg_id}_extended_fa.tex"),
                pdf_path=target_pdf,
                log_path=(run_dir / "latex" / f"{pkg_id}_extended_fa.log"),
                pdf_bytes=target_pdf.stat().st_size,
                attempts=0,
                max_attempts=max_attempts,
                fix_notes=["skipped: PDF already exists (preserved from previous phase)"],
                image_anchors_md=0,
                image_anchors_tex=0,
                image_anchors_first_in_block=True,
                generated_at=iso_now(),
            ))
            n_success += 1
            continue

        try:
            r = run_package_build(run_dir, project_root, pkg_id, max_attempts=max_attempts)
        except Exception as e:
            results.append(PackageBuildResult(
                success=False, package_id=pkg_id, env_info={},
                chosen_font="", final_fallback=SMOKE_FALLBACK_FONT, cascade=[],
                tex_path=Path("/dev/null"), pdf_path=None, log_path=None,
                pdf_bytes=0, attempts=0, max_attempts=max_attempts,
                fix_notes=[f"exception: {e!r}"],
                generated_at=iso_now(),
            ))
            n_fail += 1
            continue

        results.append(r)
        if r.success:
            n_success += 1
        else:
            n_fail += 1

    return AllPackagesResult(
        success=(n_fail == 0),
        results=results,
        n_packages=len(md_files),
        n_success=n_success,
        n_fail=n_fail,
        generated_at=iso_now(),
    )
