"""pdf_builder_agent — Phase 5A smoke-test orchestrator.

The Phase 5A scope is intentionally narrow:
    - Detect the local XeLaTeX environment and chosen Persian font.
    - Render a self-contained minimal smoke-test .tex into
      runs/<run_id>/latex/smoke_test_fa.tex and build it into
      runs/<run_id>/package_pdfs/smoke_test_fa.pdf.
    - On a build failure, ask integrations/auto_fixer_latex.py for one
      remediation, rewrite the .tex, and retry once.
    - Surface a structured SmokeResult that scripts/build_package_pdf.py
      can summarize and that PDF_BUILD_REPORT.md is built from.

The agent intentionally does NOT consume any curated package content yet.
That comes in Phase 5B (full per-package PDFs).
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from integrations.atomic_io import atomic_write_text, iso_now
from integrations.latex_builder import (
    BuildResult,
    detect_persian_font,
    detect_xelatex,
    run_xelatex,
)
from integrations.auto_fixer_latex import propose_fix


@dataclass
class SmokeResult:
    success: bool
    env_info: dict
    chosen_font: str
    final_fallback: str
    cascade: list[str]
    tex_path: Path
    pdf_path: Path | None
    log_path: Path | None
    pdf_bytes: int
    attempts: int
    build_history: list[BuildResult] = field(default_factory=list)
    fix_notes: list[str] = field(default_factory=list)
    image_used: str = ""
    generated_at: str = ""


# --- configuration --------------------------------------------------------


def _load_font_cascade(project_root: Path) -> tuple[list[str], str]:
    """Read configs/persian_fonts.json. Return (cascade, english_inline_font).

    Cascade ordering: the JSON's `fallback_chain[*].family` in order.
    """
    cfg_path = project_root / "configs" / "persian_fonts.json"
    if not cfg_path.exists():
        # Defensive: use a reasonable default if the config is missing.
        return ["Vazirmatn", "Tahoma", "Arial"], "Arial"
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    cascade_entries = cfg.get("fallback_chain") or []
    cascade = [e.get("family") for e in cascade_entries if isinstance(e, dict) and e.get("family")]
    if not cascade:
        cascade = [cfg.get("primary", {}).get("family", "Vazirmatn")]
    english = (cfg.get("english_inline") or {}).get("family") or "Arial"
    return cascade, english


# --- TeX source for the smoke test ---------------------------------------


SMOKE_FALLBACK_FONT = "DejaVu Sans"


def _smoke_tex_source(*, main_font: str, english_font: str, image_relpath: str) -> str:
    """Return a minimal self-contained .tex source for the Phase 5A smoke test.

    Goals: exercise XeLaTeX + polyglossia + fontspec + graphicx + a small
    Persian paragraph + a small English paragraph + a graphic + a math line.
    """
    # We use polyglossia (xepersian is not required and may be missing).
    # Persian/Arabic-script characters are present so we exercise the font's
    # actual coverage rather than only Latin.
    return r"""\documentclass[12pt,a4paper]{article}

\usepackage{fontspec}
\usepackage{polyglossia}
\usepackage{graphicx}
\usepackage[a4paper, margin=2cm]{geometry}
\usepackage{xcolor}

\setdefaultlanguage{persian}
\setotherlanguage{english}

\setmainfont{""" + main_font + r"""}[Script=Arabic, Language=Default]
\newfontfamily\englishfont{""" + english_font + r"""}
\newfontfamily\persianfont{""" + main_font + r"""}[Script=Arabic]

\newcommand{\en}[1]{\textenglish{#1}}

\begin{document}

\begin{center}
{\Huge\bfseries Phase 5A — Smoke Test}\\[0.5ex]
{\large integrated\_learning\_video\_factory}
\end{center}

\bigskip

\noindent\textbf{1. Persian RTL paragraph:}\par
این یک متن آزمایشی فارسی برای آزمون محیط است. هدف فقط این است که موتور
XeLaTeX و polyglossia بتوانند یک پاراگراف ساده‌ی راست‌به‌چپ را با
فونت موجود رندر کنند. ML \en{(Machine Learning)} یعنی یادگیری از داده.

\medskip

\noindent\textbf{2. English paragraph (inline LTR test):}\par
\begin{english}
This is a short English paragraph. It exercises the english font family
and verifies that Latin script renders cleanly. End of test sentence.
\end{english}

\medskip

\noindent\textbf{3. Image inclusion (one slide screenshot):}\par
\begin{center}
\includegraphics[width=0.6\linewidth]{""" + image_relpath + r"""}
\end{center}

\medskip

\noindent\textbf{4. Inline math test:}\par
A linear model: $f(x) = w_0 + w \cdot x$, with $y \in \{-1, +1\}$ for
binary classification.

\bigskip

\hrule
\medskip
\noindent\small\itshape This document is generated by
\en{agents/pdf\_builder\_agent.py} during Phase 5A. No curated package
content is rendered here yet; that is the scope of Phase 5B.

\end{document}
"""


# --- main entry -----------------------------------------------------------


def run_smoke_test(run_dir: Path | str, project_root: Path | str) -> SmokeResult:
    """Build the Phase 5A smoke-test PDF.

    Side effects:
      - writes runs/<run_id>/latex/smoke_test_fa.tex
      - writes runs/<run_id>/package_pdfs/smoke_test_fa.pdf
      - writes runs/<run_id>/latex/smoke_test_fa.log (via xelatex)
    """
    run_dir = Path(run_dir).resolve()
    project_root = Path(project_root).resolve()

    env_info = detect_xelatex()
    cascade, english_font = _load_font_cascade(project_root)
    chosen_font = detect_persian_font(cascade, final_fallback=SMOKE_FALLBACK_FONT)
    chosen_english = detect_persian_font([english_font], final_fallback=SMOKE_FALLBACK_FONT)

    latex_dir = run_dir / "latex"
    pdf_dir = run_dir / "package_pdfs"
    latex_dir.mkdir(parents=True, exist_ok=True)
    pdf_dir.mkdir(parents=True, exist_ok=True)

    # Pick an existing page screenshot for the image test. We prefer page_001.
    pages_dir = run_dir / "extracted" / "pages"
    image_relpath = "../extracted/pages/page_001.png"
    image_used = "page_001.png"
    if not (pages_dir / "page_001.png").exists():
        # Fall back to the first PNG present.
        pngs = sorted(pages_dir.glob("page_*.png"))
        if pngs:
            image_relpath = f"../extracted/pages/{pngs[0].name}"
            image_used = pngs[0].name
        else:
            image_relpath = ""  # no image; the smoke test will skip the figure
            image_used = "<none>"

    tex_path = latex_dir / "smoke_test_fa.tex"
    current_tex = _smoke_tex_source(
        main_font=chosen_font,
        english_font=chosen_english,
        image_relpath=image_relpath,
    )
    atomic_write_text(tex_path, current_tex)

    fix_notes: list[str] = []
    build_history: list[BuildResult] = []

    # Attempt 1.
    br = run_xelatex(tex_path, latex_dir)
    build_history.append(br)

    # Attempt 2 (one auto-fixer retry).
    if not br.success:
        decision = propose_fix(
            build_result=br,
            current_tex=current_tex,
            font_cascade=cascade,
            chosen_font=chosen_font,
            final_fallback=SMOKE_FALLBACK_FONT,
        )
        fix_notes.append(decision.reason + (f" — {decision.note}" if decision.note else ""))
        if decision.applied and decision.new_tex:
            current_tex = decision.new_tex
            atomic_write_text(tex_path, current_tex)
            # If the fix changed the font, also remember the new font name for
            # reporting purposes.
            br2 = run_xelatex(tex_path, latex_dir)
            build_history.append(br2)
            br = br2  # final result

    # Move/copy the produced PDF to package_pdfs/ for the canonical home.
    final_pdf_path: Path | None = None
    pdf_bytes = 0
    src_pdf = latex_dir / "smoke_test_fa.pdf"
    if src_pdf.exists() and src_pdf.stat().st_size > 0:
        target = pdf_dir / "smoke_test_fa.pdf"
        target.write_bytes(src_pdf.read_bytes())
        final_pdf_path = target
        pdf_bytes = target.stat().st_size

    return SmokeResult(
        success=bool(final_pdf_path and pdf_bytes > 0),
        env_info=env_info,
        chosen_font=chosen_font,
        final_fallback=SMOKE_FALLBACK_FONT,
        cascade=cascade,
        tex_path=tex_path,
        pdf_path=final_pdf_path,
        log_path=br.log_path,
        pdf_bytes=pdf_bytes,
        attempts=len(build_history),
        build_history=build_history,
        fix_notes=fix_notes,
        image_used=image_used,
        generated_at=iso_now(),
    )



